"""Rebuild the editable, dependency-free SVG wireframe board."""
from pathlib import Path
from html import escape

parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="1000" viewBox="0 0 1440 1000">', '<rect width="1440" height="1000" fill="#eef0f3"/>']
def text(x,y,s,size=18,color='#222'):
    parts.append(f'<text x="{x}" y="{y}" font-family="Arial, sans-serif" font-size="{size}" fill="{color}">{escape(s)}</text>')
def box(x,y,w,h,label='',fill='white'):
    parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{fill}" stroke="#737780"/>')
    if label: text(x+16,y+32,label)
